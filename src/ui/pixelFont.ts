export const GLYPH_H = 7;
const GLYPH_W = 5;
const GAP = 1;

export function textWidth(text: string): number {
  return text.length * (GLYPH_W + GAP) - GAP;
}

/** Draw text with its top-left at (x, y). Unknown characters (like spaces) are left blank. */
export function drawText(buf: PixelBuffer, text: string, x: number, y: number, color: number): void {
  [...text.toUpperCase()].forEach((ch, i) => {
    const glyph = GLYPHS[ch];
    if (!glyph) return;
    glyph.forEach((row, gy) => {
      for (let gx = 0; gx < GLYPH_W; gx++) if (row[gx] === '#') buf.set(x + i * (GLYPH_W + GAP) + gx, y + gy, color);
    });
  });
}
