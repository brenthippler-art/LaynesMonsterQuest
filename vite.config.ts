import { readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { defineConfig, type Plugin } from 'vite';

/**
 * Dev-only: Vite's hot reload talks to the local dev server over a WebSocket,
 * which our strict `connect-src 'none'` would block. While running `npm run dev`
 * we allow connecting back to the SAME dev server only. `npm run build` never
 * runs this plugin, so the shipped game keeps the exact strict policy.
 */
function allowHotReloadInDev(): Plugin {
  return {
    name: 'lmq-dev-csp-allow-hmr',
    apply: 'serve',
    transformIndexHtml(html) {
      return html.replace("connect-src 'none'", "connect-src 'self' ws://localhost:* ws://127.0.0.1:*");
    },
  };
}

/**
 * Dev-only pages, never part of `npm run build`:
 *   /gallery  → the monster gallery (gallery.html)
 *   /devices  → the game at iPad and phone sizes side by side (devices.html)
 */
function devPages(): Plugin {
  return {
    name: 'lmq-dev-pages',
    apply: 'serve',
    configureServer(server) {
      server.middlewares.use((req, _res, next) => {
        if (req.url === '/gallery' || req.url === '/gallery/') req.url = '/gallery.html';
        if (req.url === '/devices' || req.url === '/devices/') req.url = '/devices.html';
        next();
      });
    },
  };
}

function listFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? listFiles(full) : [full];
  });
}

/**
 * Build-only: writes dist/sw.js, a small service worker that keeps copies of
 * the game's OWN files so it works offline once installed. It only ever
 * handles requests to our own site (there aren't any others anyway).
 */
function offlineServiceWorker(): Plugin {
  return {
    name: 'lmq-service-worker',
    apply: 'build',
    generateBundle(_options, bundle) {
      const built = Object.keys(bundle).filter((f) => f !== 'index.html');
      const publicFiles = listFiles('public').map((f) => relative('public', f).split(sep).join('/'));
      const files = ['/', ...[...built, ...publicFiles].map((f) => '/' + f)];
      // The cache name changes whenever any file name changes (new build = fresh cache).
      let hash = 0;
      for (const ch of files.join('|')) hash = (hash * 31 + ch.charCodeAt(0)) | 0;
      const version = (hash >>> 0).toString(36);

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: `// Generated by vite.config.ts. Keeps the game's own files for offline play.
const CACHE = 'lmq-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  const url = new URL(request.url);
  // Only our own site. Anything else is left alone (and the game never asks for anything else).
  if (request.method !== 'GET' || url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    // The page itself: try for the newest version, fall back to the saved copy when offline.
    // Only a GOOD copy of the game's page is saved (never an error page from a mistyped address).
    const isGamePage = url.pathname === '/' || url.pathname === '/index.html';
    event.respondWith(
      fetch(request)
        .then((response) => {
          if (response.ok && isGamePage) {
            const copy = response.clone();
            caches.open(CACHE).then((c) => c.put('/', copy));
          }
          return response;
        })
        .catch(() => caches.match('/', { ignoreVary: true })),
    );
    return;
  }
  // Everything else (scripts, styles, icons): saved copy first, network if we don't have it.
  // ignoreVary: the page asks for its script and styles with an "Origin" note (they're marked
  // crossorigin), but the saved copies were stored without one. Servers that answer
  // "Vary: Origin" would make those look like different files, and offline the game would
  // load as a blank page. These are our own fixed files, so the note doesn't matter.
  event.respondWith(
    caches.match(request, { ignoreVary: true }).then((hit) => hit || fetch(request).then((response) => {
      if (response.ok) {
        const copy = response.clone();
        caches.open(CACHE).then((c) => c.put(request, copy));
      }
      return response;
    })),
  );
});
`,
      });
    },
  };
}

export default defineConfig({
  plugins: [allowHotReloadInDev(), devPages(), offlineServiceWorker()],
  build: {
    // Vite normally adds a tiny helper that fetch()es "preload" links. We have none,
    // so leave it out: the game's own code then contains no network calls at all.
    modulePreload: { polyfill: false },
  },
});
